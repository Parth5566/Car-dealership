CREATE TABLE IF NOT EXISTS nw_blog_posts (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(160) NOT NULL UNIQUE,
  title VARCHAR(160) NOT NULL DEFAULT '',
  excerpt VARCHAR(320) NOT NULL DEFAULT '',
  category VARCHAR(30) NOT NULL DEFAULT 'buying',
  author_name VARCHAR(100) NOT NULL DEFAULT 'NCR Wheelz',
  body JSON NOT NULL,
  seo_title VARCHAR(160) NOT NULL DEFAULT '',
  seo_description VARCHAR(320) NOT NULL DEFAULT '',
  cover_id BIGINT UNSIGNED NULL,
  cover_alt VARCHAR(200) NOT NULL DEFAULT '',
  status ENUM('draft','published','archived') NOT NULL DEFAULT 'draft',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NOT NULL,
  published_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_blog_public (status,published_at),
  FOREIGN KEY(created_by) REFERENCES nw_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS nw_blog_media (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  post_id BIGINT UNSIGNED NOT NULL,
  storage_key VARCHAR(100) NOT NULL,
  width SMALLINT UNSIGNED NOT NULL,
  height SMALLINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(post_id) REFERENCES nw_blog_posts(id) ON DELETE CASCADE,
  INDEX(post_id)
) ENGINE=InnoDB;
